-- Assignment 1: 21 entities + OperatorPhone + TripDriverAssignment = 23 relations.
-- Explicit, minimal refinements for Assignment 2:
--   booking.discount_amount_applied preserves historical discounts (SC18)
--   driver.license_class supports a simplified qualification check (SC10)
--   trip.available_seats is a maintained derived attribute (Assignment 2 §2.2.2).
-- Run ON A NEW/EMPTY Neon database; DDL intentionally does not drop existing tables.
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE user_account (
  account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE CHECK (email ~* '^[[:alnum:]._%+-]+@[[:alnum:].-]+[.][[:alpha:]]{2,}$'),
  password_hash text NOT NULL CHECK (length(password_hash)>=20),
  full_name text NOT NULL CHECK (length(btrim(full_name)) >= 2),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','DISABLED')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE passenger_profile (
  account_id bigint PRIMARY KEY REFERENCES user_account(account_id) ON DELETE RESTRICT,
  loyalty_points int NOT NULL DEFAULT 0 CHECK(loyalty_points>=0),
  preferred_contact text NOT NULL DEFAULT 'EMAIL' CHECK(preferred_contact IN ('EMAIL','PHONE'))
);
CREATE TABLE platform_admin (
  account_id bigint PRIMARY KEY REFERENCES user_account(account_id) ON DELETE RESTRICT,
  admin_level text NOT NULL CHECK(admin_level IN ('SUPPORT','MANAGER','SUPERADMIN')),
  appointed_on date NOT NULL DEFAULT current_date
);
CREATE TABLE bus_operator (
  operator_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_name text NOT NULL UNIQUE CHECK(length(btrim(operator_name))>=2),
  email text NOT NULL CHECK (email ~* '^[[:alnum:]._%+-]+@[[:alnum:].-]+[.][[:alpha:]]{2,}$'),
  status text NOT NULL DEFAULT 'APPROVED' CHECK(status IN ('PENDING','APPROVED','SUSPENDED')),
  approved_by bigint REFERENCES platform_admin(account_id) ON DELETE RESTRICT
);
CREATE TABLE operator_staff (
  account_id bigint PRIMARY KEY REFERENCES user_account(account_id) ON DELETE RESTRICT,
  operator_id bigint NOT NULL REFERENCES bus_operator(operator_id),
  employee_code text NOT NULL CHECK(length(btrim(employee_code))>0),
  hired_on date NOT NULL,
  supervisor_id bigint REFERENCES operator_staff(account_id) DEFERRABLE INITIALLY IMMEDIATE,
  UNIQUE(operator_id,employee_code),
  CHECK(supervisor_id IS DISTINCT FROM account_id)
);
CREATE TABLE operator_phone (
  operator_id bigint NOT NULL REFERENCES bus_operator(operator_id) ON DELETE CASCADE,
  phone_number text NOT NULL CHECK(phone_number ~ '^[+]?[0-9]{9,15}$'),
  PRIMARY KEY(operator_id,phone_number)
);
CREATE TABLE driver (
  driver_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id bigint NOT NULL REFERENCES bus_operator(operator_id),
  full_name text NOT NULL,
  license_no text NOT NULL UNIQUE,
  license_class text NOT NULL CHECK(license_class IN ('D','E')),
  license_expiry date NOT NULL
);
CREATE TABLE bus (
  bus_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id bigint NOT NULL REFERENCES bus_operator(operator_id),
  license_plate text NOT NULL UNIQUE,
  bus_type text NOT NULL CHECK(bus_type IN ('STANDARD','LIMOUSINE','SLEEPER')),
  deck_count int NOT NULL DEFAULT 1 CHECK(deck_count BETWEEN 1 AND 2)
);
CREATE TABLE seat (
  seat_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bus_id bigint NOT NULL REFERENCES bus(bus_id),
  seat_code text NOT NULL,
  deck_no int NOT NULL CHECK(deck_no BETWEEN 1 AND 2),
  seat_class text NOT NULL CHECK(seat_class IN ('STANDARD','VIP')),
  UNIQUE(bus_id,seat_code)
);
CREATE TABLE station (
  station_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station_name text NOT NULL,
  street text NOT NULL,
  ward text NOT NULL,
  city text NOT NULL,
  province text NOT NULL
);
CREATE TABLE route (
  route_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id bigint NOT NULL REFERENCES bus_operator(operator_id),
  origin_station_id bigint NOT NULL REFERENCES station(station_id),
  destination_station_id bigint NOT NULL REFERENCES station(station_id),
  distance_km numeric(9,2) NOT NULL CHECK(distance_km>0),
  CHECK(origin_station_id <> destination_station_id)
);
CREATE TABLE route_stop (
  route_id bigint NOT NULL REFERENCES route(route_id) ON DELETE CASCADE,
  stop_order int NOT NULL CHECK(stop_order>0),
  station_id bigint NOT NULL REFERENCES station(station_id),
  offset_minutes int NOT NULL CHECK(offset_minutes >= 0),
  pickup_allowed boolean NOT NULL DEFAULT true,
  dropoff_allowed boolean NOT NULL DEFAULT true,
  PRIMARY KEY(route_id,stop_order)
);
CREATE TABLE trip (
  trip_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_id bigint NOT NULL REFERENCES route(route_id),
  bus_id bigint NOT NULL REFERENCES bus(bus_id),
  departure_at timestamptz NOT NULL,
  arrival_at timestamptz NOT NULL,
  base_fare numeric(12,2) NOT NULL CHECK(base_fare>=0),
  status text NOT NULL DEFAULT 'SCHEDULED' CHECK(status IN ('SCHEDULED','IN_PROGRESS','COMPLETED','CANCELLED')),
  available_seats int NOT NULL DEFAULT 0 CHECK(available_seats>=0),
  CHECK(arrival_at>departure_at),
  CONSTRAINT ex_bus_no_overlapping_trips EXCLUDE USING gist
  (bus_id WITH =, tstzrange(departure_at,arrival_at,'[)') WITH &&)
  WHERE (status <> 'CANCELLED')
);
CREATE TABLE trip_seat (
  trip_id bigint NOT NULL REFERENCES trip(trip_id) ON DELETE CASCADE,
  seat_id bigint NOT NULL REFERENCES seat(seat_id),
  is_blocked boolean NOT NULL DEFAULT false,
  fare_override numeric(12,2) CHECK(fare_override IS NULL OR fare_override>=0),
  PRIMARY KEY(trip_id,seat_id)
);
CREATE TABLE trip_driver_assignment (
  trip_id bigint NOT NULL REFERENCES trip(trip_id) ON DELETE CASCADE,
  driver_id bigint NOT NULL REFERENCES driver(driver_id),
  role text NOT NULL CHECK(role IN ('PRIMARY','RELIEF')),
  assigned_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(trip_id,driver_id)
);
CREATE TABLE promotion (
  promotion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  promo_code text NOT NULL UNIQUE,
  discount_type text NOT NULL CHECK(discount_type IN ('PERCENT','FIXED')),
  discount_value numeric(12,2) NOT NULL CHECK(discount_value>0),
  valid_from timestamptz NOT NULL,
  valid_until timestamptz NOT NULL,
  usage_limit int NOT NULL CHECK(usage_limit>=0),
  CHECK(valid_until>valid_from),
  CHECK(discount_type<>'PERCENT' OR discount_value<=100)
);
CREATE TABLE booking (
  booking_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  passenger_account_id bigint NOT NULL REFERENCES passenger_profile(account_id),
  trip_id bigint NOT NULL REFERENCES trip(trip_id),
  promotion_id bigint REFERENCES promotion(promotion_id),
  booked_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','PAID','EXPIRED','CANCELLED')),
  discount_amount_applied numeric(12,2) NOT NULL DEFAULT 0 CHECK(discount_amount_applied>=0),
  total_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK(total_amount>=0),
  UNIQUE(booking_id,trip_id),
  CHECK(expires_at>booked_at)
);
CREATE TABLE ticket (
  ticket_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL,
  trip_id bigint NOT NULL,
  seat_id bigint NOT NULL,
  traveller_name text NOT NULL CHECK(length(btrim(traveller_name))>=2),
  pickup_stop_order int NOT NULL,
  dropoff_stop_order int NOT NULL,
  fare_at_booking numeric(12,2) NOT NULL CHECK(fare_at_booking>=0),
  status text NOT NULL DEFAULT 'HELD' CHECK(status IN ('HELD','CONFIRMED','USED','CANCELLED')),
  FOREIGN KEY(booking_id,trip_id) REFERENCES booking(booking_id,trip_id),
  FOREIGN KEY(trip_id,seat_id) REFERENCES trip_seat(trip_id,seat_id),
  CHECK(pickup_stop_order<dropoff_stop_order)
);
-- Declarative constraint handles concurrent inserts; not a race-prone trigger.
CREATE UNIQUE INDEX uq_trip_seat_taken ON ticket(trip_id,seat_id)
  WHERE status IN ('HELD','CONFIRMED','USED');
CREATE TABLE payment_method (
  method_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  method_name text NOT NULL,
  provider text NOT NULL,
  UNIQUE(method_name,provider)
);
CREATE TABLE payment (
  payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL REFERENCES booking(booking_id),
  method_id bigint NOT NULL REFERENCES payment_method(method_id),
  amount numeric(12,2) NOT NULL CHECK(amount>0),
  payment_status text NOT NULL CHECK(payment_status IN ('PENDING','CAPTURED','FAILED')),
  transaction_ref text UNIQUE,
  paid_at timestamptz
);
CREATE TABLE refund (
  refund_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id bigint NOT NULL UNIQUE REFERENCES payment(payment_id),
  amount numeric(12,2) NOT NULL CHECK(amount>0),
  refund_status text NOT NULL CHECK(refund_status IN ('REQUESTED','APPROVED','REJECTED')),
  requested_at timestamptz NOT NULL DEFAULT now(),
  reason text NOT NULL
);
CREATE TABLE invoice (
  invoice_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL UNIQUE REFERENCES booking(booking_id),
  billing_name text NOT NULL,
  tax_code text,
  issued_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE review (
  review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id bigint NOT NULL UNIQUE REFERENCES booking(booking_id),
  rating int NOT NULL CHECK(rating BETWEEN 1 AND 5),
  comment text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_trip_departure ON trip(departure_at);
CREATE INDEX ix_booking_trip ON booking(trip_id);
CREATE INDEX ix_payment_booking ON payment(booking_id);
CREATE INDEX ix_ticket_booking ON ticket(booking_id);
CREATE INDEX ix_trip_seat_trip ON trip_seat(trip_id);
COMMIT;
