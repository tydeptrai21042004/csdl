/** Interactive first-run configuration. Does not modify a database. */
import { createInterface } from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
const target='.env.local';
const rl=createInterface({input,output});
function validate(raw,label,pooled){
  const val=raw.trim().replace(/^['"]|['"]$/g,'');
  let url;
  try{url=new URL(val);}catch{throw new Error(`${label} is not a PostgreSQL URL.`);}
  if(!['postgresql:','postgres:'].includes(url.protocol)||!url.hostname.endsWith('.neon.tech'))throw new Error(`${label} must use a Neon *.neon.tech hostname.`);
  if(!url.username||!url.password||!url.pathname||url.pathname==='/')throw new Error(`${label} needs role, password and database name.`);
  if(pooled && !url.hostname.includes('-pooler.'))throw new Error(`${label}: choose Connection pooling ON in Neon Console.`);
  if(!pooled && url.hostname.includes('-pooler.'))throw new Error(`${label}: choose Connection pooling OFF in Neon Console.`);
  if(url.searchParams.get('sslmode')==='disable')throw new Error('Neon TLS cannot be disabled.');
  if(!url.searchParams.has('sslmode'))url.searchParams.set('sslmode','require');
  return url;
}
const quote=s=>JSON.stringify(s);
try{
 console.log('Neon Console -> Project -> Connect. Copy pooled URL first, then direct URL for the SAME branch.');
 const pool=validate(process.env.NEON_POOLED_URL || await rl.question('Pooled DATABASE_URL: '),'DATABASE_URL',true);
 const direct=validate(process.env.NEON_DIRECT_URL || await rl.question('Direct DATABASE_URL_UNPOOLED: '),'DATABASE_URL_UNPOOLED',false);
 if(pool.hostname.replace('-pooler.','.')!==direct.hostname || pool.username!==direct.username || pool.pathname!==direct.pathname){
   throw new Error('The two Neon URLs must use the same endpoint/role/database.');
 }
 if(existsSync(target)) {
   const yes=(await rl.question('.env.local exists. Replace it? [y/N] ')).trim().toLowerCase();
   if(yes!=='y') {console.log('No changes made.');process.exit(0);}
 }
 const old=existsSync(target)?readFileSync(target,'utf8'):'';
 const oldValue=(key)=>new RegExp(`^${key}=[\"']?([^\"'\n]*)`, 'm').exec(old)?.[1];
 const secret=(key,bytes)=>{const v=oldValue(key);return v?.length>=24?v:randomBytes(bytes).toString('hex');};
 const content=[
   '# Generated by npm run neon:configure; DO NOT COMMIT',
   `DATABASE_URL=${quote(pool.toString())}`,
   `DATABASE_URL_UNPOOLED=${quote(direct.toString())}`,
   `ADMIN_PASSWORD=${quote(secret('ADMIN_PASSWORD',24))}`,
   `SESSION_SECRET=${quote(secret('SESSION_SECRET',32))}`,
   `SETUP_TOKEN=${quote(secret('SETUP_TOKEN',32))}`,
   ''
 ].join('\n');
 writeFileSync(target,content,{mode:0o600});
 console.log('Saved .env.local with the two Neon URLs and application secrets.');
 console.log('Next: npm install && npm run db:check && npm run db:init && npm run dev');
 }catch(e){console.error('Configuration rejected:',e.message);process.exitCode=1;}
 finally{rl.close();}
