import {readFileSync,existsSync} from 'node:fs';
import {resolve} from 'node:path';
const schema=readFileSync(resolve('database/01_schema.sql'),'utf8');
const logic=readFileSync(resolve('database/02_logic.sql'),'utf8');
const seed=readFileSync(resolve('database/03_seed.sql'),'utf8');
const cases=readFileSync(resolve('src/lib/lab-cases.ts'),'utf8');
const tables=[...schema.matchAll(/CREATE TABLE\s+(\w+)\s*\(/gi)].map(m=>m[1]);
const procedures=[...logic.matchAll(/CREATE OR REPLACE PROCEDURE\s+(\w+)/gi)].map(m=>m[1]);
const triggers=[...logic.matchAll(/CREATE (?:CONSTRAINT )?TRIGGER\s+(\w+)/gi)].map(m=>m[1]);
let errors=[];
if(tables.length!==23||new Set(tables).size!==23)errors.push('Expected 23 unique SQL tables.');
if(procedures.length<12)errors.push(`Expected at least 12 procedures; got ${procedures.length}.`);
for(const name of ['fn_driver_workload_hours','fn_passenger_captured_spend'])if(!logic.includes('CREATE OR REPLACE FUNCTION '+name))errors.push('Missing cursor function '+name);
for(let n=1;n<=18;n++)if(!cases.includes(`id:'sc${String(n).padStart(2,'0')}'`))errors.push('Missing UI constraint test SC'+n);
for(const f of ['src/app/lab/page.tsx','src/app/setup/page.tsx','src/app/api/lab/route.ts','src/generated/db-bundle.ts'])if(!existsSync(resolve(f)))errors.push('Missing '+f);
const seededTables=[...seed.matchAll(/INSERT INTO\s+(\w+)/gi)].map(m=>m[1]);
for(const t of tables)if(!seededTables.includes(t) && !(t==='trip_seat' && logic.includes('CREATE TRIGGER seed_trip_seats')))errors.push('No INSERT or seed trigger for '+t);
console.log(JSON.stringify({tables:tables.length,procedures:procedures.length,triggers:triggers.length,seededTables:new Set(seededTables).size,semanticTests:18,errors},null,2));
if(errors.length)process.exit(1);
